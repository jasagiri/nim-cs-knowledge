## api_sections [--root:<repo>] [--check]
##
## Writes the "Public API" section of every details page from the exported symbols of the page's
## module, as `nim jsondoc` reports them, so a reader sees every signature without opening src/.
## The section is derived text (ADR-NCK-0003): edit the module, then run `nim apiSections`.
## With --check it writes nothing and exits 1 when a page differs from what it would write.
## Exit 0 on success, 2 on a usage error or when jsondoc fails.

import std/[json, os, osproc, parseopt, strutils]
import nimcs/dataset
import page_index

const
  Heading = "## Public API"
  Next = "## Laws and invariants"

func collapse(s: string): string {.raises: [].} =
  ## Runs of whitespace become one space; none is kept just inside brackets.
  for c in s:
    if c in Whitespace:
      if result.len > 0 and result[^1] notin {' ', '[', '('}: result.add ' '
    elif c in {']', ')'} and result.len > 0 and result[^1] == ' ':
      result[^1] = c
    else:
      result.add c
  result = result.strip

func dropTrailingPragma(code: string): string {.raises: [].} =
  ## `func f(x: int): int {.raises: [].}` → `func f(x: int): int`. Pragmas inside the parameter
  ## list (a closure's `{.noSideEffect.}`) stay: a caller has to match them.
  let s = code.strip
  if not s.endsWith(".}"): return s
  var depth = 0
  var i = s.len - 1
  while i > 0:
    if s[i] == '}' and s[i - 1] == '.': inc depth
    elif s[i] == '.' and s[i - 1] == '{':
      dec depth
      if depth == 0: return s[0 ..< i - 1].strip
    dec i
  s

func line(kind, code: string): string {.raises: [].} =
  case kind
  of "skType": "type " & code.strip
  of "skConst": "const " & collapse(code)
  of "skLet": "let " & collapse(code)
  of "skVar": "var " & collapse(code)
  else: collapse(dropTrailingPragma(code))

proc jsondocAll(root, work: string; modules: seq[string]): bool =
  ## Runs `nim jsondoc` on every module at once, one output directory per module; false when one fails.
  var cmds: seq[string]
  for m in modules:
    cmds.add "nim jsondoc --hints:off --outdir:" & quoteShell(work / m.changeFileExt("")) & " " &
      quoteShell(root / m)
  var failed = false
  let rc = execProcesses(cmds, options = {poStdErrToStdOut, poEvalCommand, poParentStreams},
    n = countProcessors(),
    afterRunEvent = proc(idx: int; p: Process) =
      if p.peekExitCode != 0:
        stderr.writeLine "api_sections: jsondoc failed on " & modules[idx]
        failed = true)
  rc == 0 and not failed

proc symbols(work, module: string): (seq[string], bool) =
  ## The module's exported symbols in source order; false when its jsondoc output cannot be read.
  let path = work / module.changeFileExt("") / module.extractFilename.changeFileExt("json")
  try:
    for e in parseFile(path)["entries"]:
      result[0].add line(e["type"].getStr, e["code"].getStr)
    result[1] = true
  except CatchableError as ex:
    stderr.writeLine "api_sections: cannot read " & path & ": " & ex.msg

func section(module: string; syms: seq[string]): string {.raises: [].} =
  let imp = module.replace("src/", "").changeFileExt("")
  result = Heading & "\n\nEvery exported symbol of `" & module & "`, generated by `nim apiSections` (the\n" &
    "tests fail when it drifts). `import " & imp & "` brings these names. A type they use from\n" &
    "another module (`Option`, `Result`, `Graph`) needs that module's import too, as in the example\n" &
    "above. A field marked `*` is readable outside the module; a type shown without fields is opaque,\n" &
    "built and read only through the functions.\n\n"
  if syms.len == 0:
    result.add "The module exports nothing.\n"
  else:
    result.add "```text\n" & syms.join("\n") & "\n```\n"

func withSection(page, sec: string): string {.raises: [].} =
  ## The page with its Public API section replaced, or inserted before Laws and invariants.
  let at = page.find("\n" & Heading & "\n")
  if at >= 0:
    let stop = page.find("\n## ", at + 1 + Heading.len)
    return page[0 .. at] & sec & page[stop .. ^1]
  let nx = page.find("\n" & Next & "\n")
  if nx < 0: return page
  page[0 .. nx] & sec & "\n" & page[nx + 1 .. ^1]

proc main(): int =
  var root = currentSourcePath().parentDir.parentDir
  var checkOnly = false
  for kind, key, val in getopt():
    case kind
    of cmdLongOption, cmdShortOption:
      case key
      of "root": root = val
      of "check": checkOnly = true
      else:
        stderr.writeLine "api_sections: unknown option --" & key
        return 2
    of cmdArgument:
      stderr.writeLine "api_sections: unexpected argument " & key
      return 2
    of cmdEnd: discard # getopt never yields cmdEnd inside the loop
  let work = getTempDir() / "nck-jsondoc-" & $getCurrentProcessId()
  createDir(work)
  defer: removeDir(work)
  let pages = collect(root)
  var modules: seq[string]
  for c in pages:
    if c.modulePath.len > 0 and c.modulePath notin modules: modules.add c.modulePath
  if not jsondocAll(root, work, modules): return 2
  var drift = 0
  for c in pages:
    if c.modulePath.len == 0: continue
    let (syms, ok) = symbols(work, c.modulePath)
    if not ok: return 2
    let want = withSection(c.page, section(c.modulePath, syms))
    if want == c.page: continue
    inc drift
    if checkOnly: stderr.writeLine "api_sections: out of date: " & c.pagePath
    else: writeFile(root / c.pagePath, want)
  if checkOnly and drift > 0: return 1
  echo "api_sections: ", drift, if checkOnly: " pages differ" else: " pages written"
  0

when isMainModule:
  quit main()
